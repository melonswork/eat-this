"""Make port/src/frontend/helpfont.rs: the 1-bit glyphs of the help pages' font.

    uv run python tools/helpfont.py LiberationSans-Bold.ttf > port/src/frontend/helpfont.rs

The original asks GDI for Arial, weight 700, cell height 16: Arial Bold at 14 pixels per em (its
VDMX table: the largest size at most 16 high; ascent 13, descent 3). Liberation Sans Bold has the
same advances (ARIAL below: the exceptions) and a free licence (OFL 1.1), so its hinted monochrome bitmaps can be in the repo.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

PPEM, ASCENT, HEIGHT = 14, 13, 16
# Arial Bold's hinted advance where Liberation Sans Bold 2.1.5's differs.
ARIAL = {"-": 4, "\xad": 4}


def glyph(font, ch):
    """(advance, left, 16 rows of 16 bits, bit 15 = the pixel at `left`)."""
    adv = ARIAL.get(ch) or round(font.getlength(ch, mode="1"))
    img = Image.new("1", (32, HEIGHT))
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((8, ASCENT), ch, fill=1, font=font, anchor="ls")
    box = img.getbbox()
    left = box[0] - 8 if box else 0
    rows = [sum(0x8000 >> x for x in range(16) if img.getpixel((left + 8 + x, y))) for y in range(HEIGHT)]
    return adv, left, rows


def main():
    font = ImageFont.truetype(sys.argv[1], PPEM, layout_engine=ImageFont.Layout.BASIC)
    print("//! Generated by tools/helpfont.py from Liberation Sans Bold (digitized data copyright (c) 2010")
    print("//! Google Corporation, copyright (c) 2012 Red Hat, Inc.; SIL Open Font License 1.1), 14 pixels per em, hinted, 1 bit: see that tool. Not edited by hand.")
    print()
    print("/// Latin-1 0x20..0xff: (advance, left bearing, 16 rows from the cell's top; bit 15 = leftmost).")
    print("pub const GLYPHS: [(u8, i8, [u16; 16]); 224] = [")
    for c in range(0x20, 0x100):
        ch = chr(c) if not 0x7F <= c < 0xA0 else " "
        adv, left, rows = glyph(font, ch)
        print(f"    ({adv}, {left}, [{', '.join(f'0x{r:04x}' if r else '0' for r in rows)}]),")
    print("];")


if __name__ == "__main__":
    main()
